//! Delivery: the podcast pipeline (through the existing hub) and the typing
//! drill on typer.marcpartensky.com.
//!
//! Nothing here generates audio or video: the hub already owns the queue, the
//! Open Notebook notebooks and the Audiobookshelf upload. mnemo only hands it
//! the score and the explanation sheet, which is exactly the `analysis` field
//! the queue already carries.

use crate::config::Config;
use crate::model::{Brief, Score};
use crate::R;
use serde_json::{json, Value};

fn hub_token(cfg: &Config) -> R<String> {
    Ok(std::fs::read_to_string(&cfg.hub_token_file)?.trim().to_string())
}

/// Enqueue the conversation in the podcast hub and hand it the gaps plus the
/// brief, so the episode is built from mnemo's reading instead of a fresh one.
pub async fn to_podcast(cfg: &Config, score: &Score, brief: Option<&Brief>) -> R<String> {
    let token = hub_token(cfg)?;
    let client = reqwest::Client::new();
    let base = cfg.hub_url.trim_end_matches('/');

    let title = if score.title.is_empty() {
        score.sujet.clone()
    } else {
        score.title.clone()
    };
    let item = json!({
        "id": score.id,
        "title": title,
        "sujet": score.sujet,
        "objectif": score.objectif,
        "kind": "retention",
        "score": score.priorite.round() as i64,
        "source": "mnemo",
        "started_at": score.started_at,
        "matiere": score.matiere,
        "ignorance": score.ignorance,
        "focus": score.focus,
        "domaine": score.domaine,
        "importance": score.importance,
        "points": score.points,
        "points_liste": score.points_liste,
    });
    let resp = client
        .post(format!("{base}/queue"))
        .header("X-Hub-Token", &token)
        .json(&item)
        .send()
        .await?;
    if !resp.status().is_success() {
        return Err(format!("hub /queue HTTP {}", resp.status()).into());
    }

    let gaps: Vec<Value> = score
        .gaps
        .iter()
        .map(|g| json!({"point": g.point, "quote": g.quote, "to_explain": g.to_explain}))
        .collect();
    let mut analysis = json!({
        "question": score.title,
        "answered": score.objectif,
        "gaps": gaps,
        "facts": [],
        "wikipedia": [],
        "terms": score.terms,
        "analyst": "mnemo",
    });
    if let Some(brief) = brief {
        analysis["brief"] = json!(brief.body);
        analysis["brief_title"] = json!(brief.title);
    }
    let resp = client
        .patch(format!("{base}/queue/{}", score.id))
        .header("X-Hub-Token", &token)
        .json(&json!({ "analysis": analysis.to_string() }))
        .send()
        .await?;
    if !resp.status().is_success() {
        return Err(format!("hub PATCH HTTP {}", resp.status()).into());
    }
    Ok(format!("{base}/queue/{}", score.id))
}

/// Write the typing word list. typer serves `lang/<name>` as one word per line;
/// the index next to it is what its front-end reads to offer the drill.
pub fn to_typer(cfg: &Config, terms: &[String]) -> R<String> {
    if terms.is_empty() {
        return Err("no term to write".into());
    }
    std::fs::create_dir_all(&cfg.typer_dir)?;
    let list = cfg.typer_dir.join("mnemo");
    let mut body = String::from(
        "# generated by mnemo: the vocabulary of Marc's own conversations\n",
    );
    for term in terms {
        let clean = term.trim().to_lowercase().replace(' ', "-");
        if clean.len() >= 2 && clean.len() <= 24 {
            body.push_str(&clean);
            body.push('\n');
        }
    }
    std::fs::write(&list, body)?;

    let index = cfg.typer_dir.join("index.json");
    std::fs::write(
        &index,
        serde_json::to_string_pretty(&json!({
            "generated_at": now(),
            "lists": [{"id": "mnemo", "label": "vocabulaire mnemo", "group": "Mnemo",
                       "file": "mnemo", "words": terms.len()}]
        }))?,
    )?;
    Ok(list.to_string_lossy().to_string())
}

/// A copy of the whole brief as a markdown file: the site can serve it, and
/// nothing depends on the database being up to read it.
pub fn brief_file(cfg: &Config, brief: &Brief) -> R<String> {
    let dir = &cfg.brief_dir;
    std::fs::create_dir_all(dir)?;
    let safe: String = brief
        .session_id
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '-')
        .collect();
    let path = dir.join(format!("{safe}.md"));
    std::fs::write(&path, format!("# {}\n\n{}\n", brief.title, brief.body))?;
    Ok(path.to_string_lossy().to_string())
}

pub fn now() -> f64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs_f64())
        .unwrap_or(0.0)
}
